/**
 * Мутации: проверка, что тесты ловят настоящие поломки, а не просто зелёные.
 *
 * Качество тестов меряется не их числом, а тем, сколько поломок они ловят.
 * Скрипт по очереди портит одну строку в коде (мутант), гоняет тесты
 * и смотрит, покраснел ли набор.
 *
 * Запуск:
 *   node tools/mutate.mjs                    # все мутанты из tools/mutants.json
 *   node tools/mutate.mjs digTaps            # только мутанты, в чьём id есть строка
 *   node tools/mutate.mjs --jobs 6           # копий проекта, по умолчанию 4
 *   node tools/mutate.mjs --workers 2        # потоков vitest в каждой копии
 *   node tools/mutate.mjs --list файл.json   # другой список мутантов
 *
 * Выжил мутант — в тестах пробел: поведение сломано, а набор молчит.
 * Такой пробел закрывается кейсом в существующем файле тестов своей зоны.
 *
 * Как устроено (решения владельца 07.11, Б-6, Б-7, Б-8):
 * - Мутант портит не рабочее дерево, а одну из копий проекта во
 *   временном каталоге системы (`<tmp>/diplodok-mutate-<хеш>/w<i>/`; под
 *   node_modules `vitest related` слеп); копии работают параллельно. Исходники
 *   и их время правки прогон не трогает, хук before-stop не будится.
 * - Сперва узкий прогон: только тесты, импортирующие испорченный файл
 *   (`vitest related`), до первого красного. Зелёный узкий прогон — ещё не
 *   выживший: тесты, читающие файл текстом, в граф импортов не попадают,
 *   поэтому такого мутанта проверяет весь набор.
 * - Пойманный мутант запоминается в `node_modules/.cache/mutate/cache.json`
 *   с ключом: определение мутанта, испорченный файл, тест, что покраснел,
 *   всё, что он импортирует и читает текстом, lock-файл, конфиги и сами
 *   скрипты мутаций. Пока ключ тот же, мутант считается пойманным без прогона.
 *   Выжившие и непримененные в кеш не попадают. Отдельного флага «забыть кеш»
 *   нет: правка скрипта меняет ключ сама.
 * - Один прогон за раз: замок `node_modules/.cache/mutate/lock` с pid.
 *
 * Логика — в `tools/mutateRun.mjs` (ход прогона) и `tools/mutateLib.mjs`
 * (ключ, замок, пути копий; тесты — `tests/mutateLib.test.ts`).
 */
import { main } from './mutateRun.mjs';

main(process.argv.slice(2)).catch((err) => {
  console.error(String(err?.message ?? err));
  process.exit(2);
});
