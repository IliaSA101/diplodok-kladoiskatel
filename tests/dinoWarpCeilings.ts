/**
 * Худшее по зоне в крайней позе: самое большое растяжение, самая малая площадь
 * (со знаком) и самое малое сжатие. Площадь грани = s1·s2 *одной* грани, а максимум
 * s1 и минимум площади в зоне — у разных, поэтому игла s1 5 / s2 0.2 проходит мимо
 * двух первых чисел: сжатие держит третье. `s2` не заведён там, где замер уже
 * у нуля (вывернутая зона, помечена в комментарии таблицы): пол из нуля ничего не говорит.
 */
export interface Peak {
  s1: number;
  det: number;
  s2?: number;
}

